// Universal translation resolver: resolves exact keys, phrase lookups, and keyword replacements
export function getTranslation(lang: AppLanguage, inputKeyOrText: string, fallback?: string): string {
  if (!inputKeyOrText) return fallback || '';
  
  const targetDict = TRANSLATIONS[lang] || TRANSLATIONS.en;
  const enDict = TRANSLATIONS.en;

  // 1. Direct dictionary key match
  if (targetDict[inputKeyOrText]) {
    return targetDict[inputKeyOrText];
  }

  // 2. Direct English value lookup match
  const trimmed = inputKeyOrText.trim();
  const lowerTrimmed = trimmed.toLowerCase();

  for (const [k, v] of Object.entries(enDict)) {
    if (v.toLowerCase() === lowerTrimmed || k.toLowerCase() === lowerTrimmed) {
      if (targetDict[k]) {
        return targetDict[k];
      }
    }
  }

  // 3. Exact matching in target dictionary values
  for (const [k, v] of Object.entries(targetDict)) {
    if (k.toLowerCase() === lowerTrimmed) {
      return v;
    }
  }

  // If fallback provided and target is English, return fallback
  if (lang === 'en') {
    return fallback || inputKeyOrText;
  }

  // 4. Return localized fallback if key was found in enDict
  if (enDict[inputKeyOrText] && targetDict[inputKeyOrText]) {
    return targetDict[inputKeyOrText];
  }

  return fallback || inputKeyOrText;
}
